async def main(list_only: bool) -> None:
    conf = appconf.load()
    vconf = conf.get("vidu") or {}
    # 与 bridge 同规: host 默认 api.vidu.com
    import os
    os.environ.setdefault("VIDU_HOST", vconf.get("host") or "api.vidu.com")
    vu.configure(vconf)

    libs = (await vu.list_action_libraries()) or {}
    items = libs.get("items") or []
    lib = next((l for l in items if l.get("name") == LIB_NAME), None)
    if not lib and list_only:
        print(f"没有名为 {LIB_NAME} 的库; 账号现有 {len(items)} 个库")
        return
    if not lib:
        r = await vu.create_action_library(LIB_NAME,
                                           description="小雅直播间弹幕动作指令集(与 dm-aliases.json 对齐)")
        lib = r.get("library") or r
        print(f"✅ 建库 {LIB_NAME}: id={lib.get('id')}")
    lib_id = str(lib.get("id"))
    if list_only:
        acts = await vu.list_actions(lib_id)
        for a in acts.get("items") or []:
            print("-", a.get("name"))
        return

    existing = {a.get("name") for a in ((await vu.list_actions(lib_id)).get("items") or [])}
    done = skip = 0
    for name, desc in ACTIONS.items():
        if name in existing:
            skip += 1
            continue
        await vu.create_action(lib_id, name, desc)
        done += 1
        print(f"  + {name}")
    print(f"✅ 完成: 新建 {done} 条, 跳过已有 {skip} 条; library_id={lib_id}")


if __name__ == "__main__":
    asyncio.run(main(list_only="--list" in sys.argv))
